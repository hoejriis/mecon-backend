#!/usr/bin/env python3
"""Writes src/mecon_reader_backend/reader_core_schemas.py from contracts/reader-core/v1/openapi.yaml.

The running facade has no YAML parser and no schema engine, so the HTTP core adapter checks answers against a
copy of the document's operations and component schemas (annotations dropped), kept in a generated module.
`tests/test_http_core.py` fails if the module differs from what this script would write now.
Run from reader-backend/:   python3 scripts/reader_core_schemas.py
"""
from __future__ import annotations

import pathlib
import pprint
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC = ROOT.parent / "contracts" / "reader-core" / "v1" / "openapi.yaml"
OUT = ROOT / "src" / "mecon_reader_backend" / "reader_core_schemas.py"
ANNOTATIONS = ("description", "examples", "example", "title", "default", "summary")


def strip(schema):
    """The schema without annotations. Property names are kept whatever they are called."""
    if isinstance(schema, list):
        return [strip(s) for s in schema]
    if not isinstance(schema, dict):
        return schema
    out = {}
    for k, v in schema.items():
        if k in ANNOTATIONS:
            continue
        if k == "properties":
            out[k] = {name: strip(sub) for name, sub in v.items()}
        else:
            out[k] = strip(v)
    return out


def ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[1]


def render() -> str:
    doc = yaml.safe_load(DOC.read_text(encoding="utf-8"))
    shared = doc["components"].get("responses", {})
    operations = {}
    for path, item in doc["paths"].items():
        for method, op in item.items():
            req = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            responses = {}
            for status, resp in op["responses"].items():
                if "$ref" in resp:
                    resp = shared[ref_name(resp["$ref"])]
                schema = resp.get("content", {}).get("application/json", {}).get("schema")
                responses[int(status)] = None if schema is None else ref_name(schema["$ref"])
            operations[op["operationId"]] = {"method": method.upper(), "path": path,
                                             "request": None if req is None else ref_name(req["$ref"]),
                                             "responses": responses}
    schemas = {name: strip(s) for name, s in doc["components"]["schemas"].items()}
    return (
        '"""contracts/reader-core/v1, as the HTTP core adapter checks answers against it. Generated by\n'
        "scripts/reader_core_schemas.py from the OpenAPI document; do not edit by hand. tests/test_http_core.py\n"
        'fails if it drifts from the document."""\n'
        f"VERSION = {doc['info']['version']!r}\n\n"
        f"OPERATIONS = {pprint.pformat(operations, width=116, sort_dicts=True)}\n\n"
        f"SCHEMAS = {pprint.pformat(schemas, width=116, sort_dicts=True)}\n"
    )


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
