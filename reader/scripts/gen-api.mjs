// Generates src/api/schema.gen.ts from the Reader API OpenAPI contract.
//   node scripts/gen-api.mjs          write the file
//   node scripts/gen-api.mjs --check  exit 1 if the committed file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const spec = new URL('../../contracts/reader-api/v1/openapi.yaml', import.meta.url);
const out = new URL('../src/api/schema.gen.ts', import.meta.url);

const HEADER = `// GENERATED by scripts/gen-api.mjs from contracts/reader-api/v1/openapi.yaml.
// Do not edit by hand; run \`npm run gen:api\`.
`;

const ast = await openapiTS(spec);
const text = HEADER + astToString(ast);

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (current !== text) {
    console.error(`${fileURLToPath(out)} is out of date; run npm run gen:api`);
    process.exit(1);
  }
  console.log('schema.gen.ts is up to date');
} else {
  writeFileSync(out, text);
  console.log(`wrote ${fileURLToPath(out)}`);
}
