// Generates the API type files from the OpenAPI contracts.
//   node scripts/gen-api.mjs          write the files
//   node scripts/gen-api.mjs --check  exit 1 if a committed file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const TARGETS = [
  { spec: '../../contracts/reader-api/v1/openapi.yaml', out: '../src/api/schema.gen.ts', rel: 'contracts/reader-api/v1/openapi.yaml' },
  { spec: '../../contracts/observations/v1/openapi.yaml', out: '../src/api/observations.gen.ts', rel: 'contracts/observations/v1/openapi.yaml' },
];

let stale = false;
for (const t of TARGETS) {
  const spec = new URL(t.spec, import.meta.url);
  const out = new URL(t.out, import.meta.url);
  const header = `// GENERATED by scripts/gen-api.mjs from ${t.rel}.
// Do not edit by hand; run \`npm run gen:api\`.
`;
  const text = header + astToString(await openapiTS(spec));
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(out, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== text) {
      console.error(`${fileURLToPath(out)} is out of date; run npm run gen:api`);
      stale = true;
    } else {
      console.log(`${t.out.split('/').pop()} is up to date`);
    }
  } else {
    writeFileSync(out, text);
    console.log(`wrote ${fileURLToPath(out)}`);
  }
}
if (stale) process.exit(1);
